#!/usr/bin/env python3
"""Download public Pix aggregates from the BCB open-data API (Olinda) and write the
calibration targets used by LoopSettle.

Only public data. Only the Python standard library.

    python data/fetch_pix.py --month 202609 --keys-date 2026-09-30

Outputs
  data/raw/pix_transacoes_<month>.csv   raw rows (NOT versioned, see .gitignore)
  data/raw/pix_chaves_<date>.csv        raw rows (NOT versioned)
  data/calibration/pix.toml             aggregates (versioned, small)

Sources
  EstatisticasTransacoesPix: monthly quantity and value by payer/payee type, nature, ...
  ChavesPix: number of Pix keys per participant (ISPB) -- used as a proxy for the
  participant size distribution (ASSUMPTION: transaction share ~ key share).
"""
import argparse
import calendar
import csv
import json
import os
import sys
import time
import urllib.parse
import urllib.request

BASE = "https://olinda.bcb.gov.br/olinda/servico/Pix_DadosAbertos/versao/v1/odata"
HERE = os.path.dirname(os.path.abspath(__file__))
TOP = 5_000_000


def get_json(url, tries=5):
    for k in range(tries):
        try:
            req = urllib.request.Request(url, headers={"User-Agent": "loopsettle-calibration/0.1"})
            with urllib.request.urlopen(req, timeout=300) as r:
                return json.load(r)
        except Exception as e:  # network hiccups: retry with backoff
            if k == tries - 1:
                raise
            print(f"  retry {k + 1}: {e}", file=sys.stderr)
            time.sleep(5 * (k + 1))


def fetch_all(resource, params, select, flt):
    # The Olinda server rejects $skip (HTTP 500), so everything comes in one request with a
    # large $top; we fail loudly if the result might have been truncated.
    q = dict(params)
    q.update({"$select": select, "$filter": flt, "$top": str(TOP), "$format": "json"})
    url = f"{BASE}/{resource}?" + urllib.parse.urlencode(q, safe="@'$,()", quote_via=urllib.parse.quote)
    rows = get_json(url)["value"]
    print(f"  {resource}: {len(rows)} rows", file=sys.stderr)
    if len(rows) >= TOP:
        sys.exit(f"result may be truncated at $top={TOP}; split the query")
    if not rows:
        sys.exit(f"no rows for {flt}; is the reference period published?")
    return rows


def write_csv(path, rows):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    if not rows:
        return
    with open(path, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--month", default="202609", help="AnoMes, e.g. 202609")
    ap.add_argument("--keys-date", default="2026-09-30", help="ChavesPix reference date")
    ap.add_argument("--top", type=int, default=1000, help="how many participant shares to keep")
    a = ap.parse_args()

    month = int(a.month)
    print(f"Fetching EstatisticasTransacoesPix for {month} ...", file=sys.stderr)
    tx = fetch_all(
        "EstatisticasTransacoesPix(Database=@Database)",
        {"@Database": f"'{month}'"},
        "AnoMes,PAG_PFPJ,REC_PFPJ,NATUREZA,VALOR,QUANTIDADE",
        f"AnoMes eq {month}",
    )
    write_csv(os.path.join(HERE, "raw", f"pix_transacoes_{month}.csv"), tx)

    print(f"Fetching ChavesPix for {a.keys_date} ...", file=sys.stderr)
    keys = fetch_all(
        "ChavesPix(Data=@Data)",
        {"@Data": f"'{a.keys_date}'"},
        "Data,ISPB,Nome,NaturezaUsuario,TipoChave,qtdChaves,Segmento",
        f"Data eq {a.keys_date}",
    )
    write_csv(os.path.join(HERE, "raw", f"pix_chaves_{a.keys_date}.csv"), keys)

    # ---- transaction aggregates
    qty = sum(int(r["QUANTIDADE"] or 0) for r in tx)
    val = sum(float(r["VALOR"] or 0.0) for r in tx)
    by_nat = {}
    for r in tx:
        k = r.get("NATUREZA") or "NA"
        q, v = by_nat.get(k, (0, 0.0))
        by_nat[k] = (q + int(r["QUANTIDADE"] or 0), v + float(r["VALOR"] or 0.0))
    days = calendar.monthrange(month // 100, month % 100)[1]

    # ---- participant concentration (keys per ISPB)
    per = {}
    seg = {}
    for r in keys:
        per[r["ISPB"]] = per.get(r["ISPB"], 0) + int(r["qtdChaves"] or 0)
        seg[r["ISPB"]] = r.get("Segmento") or ""
    ranked = sorted(per.items(), key=lambda kv: -kv[1])
    total_keys = sum(per.values())
    shares = [v / total_keys for _, v in ranked]
    hhi = sum(s * s for s in shares)
    top = lambda k: sum(shares[:k])

    out = os.path.join(HERE, "calibration", "pix.toml")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("# Generated by data/fetch_pix.py from the BCB Pix open-data API (Olinda).\n")
        f.write(f"# EstatisticasTransacoesPix AnoMes={month}; ChavesPix Data={a.keys_date}.\n")
        f.write(f"# Downloaded {time.strftime('%Y-%m-%d')} UTC-local. Public data only.\n\n")
        f.write("[source]\n")
        f.write(f"month = {month}\nkeys_date = \"{a.keys_date}\"\ndays_in_month = {days}\n")
        f.write(f"tx_rows = {len(tx)}\nkey_rows = {len(keys)}\n\n")
        f.write("[transactions]\n")
        f.write(f"monthly_count = {qty}\nmonthly_value_brl = {val:.2f}\n")
        f.write(f"daily_count = {qty / days:.1f}\ndaily_value_brl = {val / days:.2f}\n")
        f.write(f"ticket_mean_brl = {val / qty:.4f}\n")
        for k, (q, v) in sorted(by_nat.items()):
            kk = k.replace(" ", "_").replace("-", "_")
            f.write(f"share_count_{kk} = {q / qty:.6f}\nshare_value_{kk} = {v / val:.6f}\n")
        f.write("\n[participants]\n")
        f.write(f"n_with_keys = {len(ranked)}\ntotal_keys = {total_keys}\n")
        f.write(f"hhi = {hhi:.6f}\ntop5_share = {top(5):.6f}\ntop10_share = {top(10):.6f}\n")
        f.write(f"top20_share = {top(20):.6f}\ntop50_share = {top(50):.6f}\ntop200_share = {top(200):.6f}\n")
        f.write("# key shares by rank (descending), first --top participants\n")
        f.write("shares = [" + ", ".join(f"{s:.8g}" for s in shares[: a.top]) + "]\n")
        f.write("segments = [" + ", ".join('"' + seg[i].replace('"', "'") + '"' for i, _ in ranked[: a.top]) + "]\n")
    print(f"wrote {out}: {qty} tx, R$ {val:,.0f}, ticket R$ {val / qty:.2f}, {len(ranked)} participants", file=sys.stderr)


if __name__ == "__main__":
    main()
