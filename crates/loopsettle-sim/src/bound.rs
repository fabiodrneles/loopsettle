    /// The bound holds participant by participant for every delay-bounded engine.
    #[test]
    fn engines_never_beat_the_delay_bound() {
        for (seed, profile_strength) in [(1u64, 0.0), (2, 0.0), (3, 0.0), (4, 1.0), (5, 0.5)] {
            let cfg = ScenarioConfig { seed, participants: 25, payments_per_day: 40_000.0, n_big: 3, n_mid: 5, profile_strength, ..Default::default() };
            // (engine, its maximum settlement delay in ms)
            let cases = [
                ("micro:all:500:2000", 2_000u64),
                ("micro:all:1000:10000", 10_000),
                ("micro:all:5000:10000:2", 10_000),
                ("deferred:8640", 10_000),
                ("deferred:96", 900_000),
                ("deferred:24", 3_600_000),
            ];
            let mut specs = vec![EngineSpec::Gross];
            specs.extend(cases.iter().map(|(s, _)| EngineSpec::parse(s).unwrap()));
            let o = run(&cfg, &specs, &Opening::Unlimited, false, None);
            let delays: Vec<u64> = cases.iter().map(|&(_, d)| d).collect();
            let bounds = delay_bounds(&cfg, &delays);
            let floors = liquidity_floors(&cfg, &delays);
            for (k, r) in o.results[1..].iter().enumerate() {
                for i in 0..cfg.participants {
                    let ub = o.flow.ub(i as u32).max(0);
                    let saving = ub - r.liquidity_by_participant[i];
                    // The floor is the tighter statement: no engine needs less than it, and
                    // the saving it allows never exceeds the window bound.
                    assert!(
                        r.liquidity_by_participant[i] >= floors[k][i],
                        "seed {seed}, {}: participant {i} needed {} < floor {}",
                        cases[k].0,
                        r.liquidity_by_participant[i],
                        floors[k][i]
                    );
                    assert!(ub - floors[k][i] <= bounds[k][i], "floor must be at least as tight as the window bound");
                    assert!(
                        saving <= bounds[k][i],
                        "seed {seed}, {}: participant {i} saved {saving} > bound {}",
                        cases[k].0,
                        bounds[k][i]
                    );
                }
            }
        }
    }

    /// Hand example. A pays 10 at t=0 and 10 at t=5; B pays A 8 at t=7.
    /// UB_A = 20. With d = 2: at t = 7 both of A's payments are due and the 8 has arrived, so
    /// the floor is 20 - 8 = 12 (the window bound says only "saving <= 10", floor >= 10).
    /// With d = 1 the 8 arrives too late for the second deadline (t = 6): floor = 20.
    #[test]
    fn floor_hand_example() {
        use loopsettle_core::Payment;
        let p = |id, t, a, b, v| Payment { id, t_arrival: t, payer: a, payee: b, amount: v };
        let v = vec![p(0, 0, 0, 1, 10), p(1, 5, 0, 1, 10), p(2, 7, 1, 0, 8)];
        let f = liquidity_floors_from(2, || v.clone().into_iter(), &[0, 1, 2, 100]);
        assert_eq!(f[0], vec![20, 0], "d = 0 is the gross upper bound");
        assert_eq!(f[1], vec![20, 0]);
        assert_eq!(f[2], vec![12, 0]);
        assert_eq!(f[3], vec![12, 0], "a long delay tends to the end-of-period net debit");
        let w = delay_bounds_from(2, || v.clone().into_iter(), &[2]);
        assert_eq!(w[0][0], 10);
        assert!(20 - f[2][0] <= w[0][0]);
    }

